/**
 * StopType Enum
 * 
 * Rota içerisindeki durakların türlerini tanımlar.
 * - ACCOMMODATION: Konaklama yeri (otel, pansiyon, vb.)
 * - ATTRACTION: Turist çekicilik merkezi
 * - RESTAURANT: Yemek içme yeri
 * - ACTIVITY: Aktivite ve deneyim
 * - TRANSPORT: Ulaştırma ve geçiş noktası
 * - OTHER: Diğer durumlar
 */
export enum StopType {
  ACCOMMODATION = 'ACCOMMODATION',
  ATTRACTION = 'ATTRACTION',
  RESTAURANT = 'RESTAURANT',
  ACTIVITY = 'ACTIVITY',
  TRANSPORT = 'TRANSPORT',
  OTHER = 'OTHER',
}
